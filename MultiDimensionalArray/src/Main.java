public class Main {
    public static void main(String[] args) {
        int sum = 0;
        int[][] arr = {{1,6,9,6},{2,5,7,8},{2,3,8,5}};
        for (int i = 0; i < arr.length; i++) {
            for (int j = 0; j < arr[i].length; j++) {
                sum += arr[i][j];
            }
        }

        System.out.println(sum);
    }
}